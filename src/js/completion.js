/* completion.js — Download completion record as printable HTML */
'use strict';

function buildCompletionHTML() {
  const state = JSON.parse(localStorage.getItem('india-cq-v1') || '{}');
  const name   = state['learner-name']  || '(Name not entered)';
  const pre    = state['cq-pre-scores']  || {};
  const post   = state['cq-post-scores'] || {};
  const plan   = state['action-plan']    || {};
  const today  = new Date().toLocaleDateString('en-US',{year:'numeric',month:'long',day:'numeric'});

  const caps = ['drive','knowledge','strategy','action'];
  const capLabels = { drive:'CQ Drive', knowledge:'CQ Knowledge', strategy:'CQ Strategy', action:'CQ Action' };

  const scoreRows = caps.map(c => {
    const before = pre[c] ?? '—';
    const after  = post[c] ?? '—';
    const delta  = (typeof before==='number' && typeof after==='number')
                   ? (after - before > 0 ? `+${after-before}` : `${after-before}`) : '—';
    return `<tr>
      <td>${capLabels[c]}</td>
      <td style="text-align:center">${before}</td>
      <td style="text-align:center">${after}</td>
      <td style="text-align:center;font-weight:700;color:${delta.startsWith('+')?'#2e7d32':delta.startsWith('-')?'#D55E00':'#adb5bd'}">${delta}</td>
    </tr>`;
  }).join('');

  const reflectionKeys = [
    ['reflect-m1','Module 1 — Cultural Dimensions'],
    ['reflect-m2','Module 2 — Business Culture'],
    ['reflect-m3','Module 3 — Leadership Culture'],
    ['reflect-m4-defaults','Module 4 — Self-Reflection'],
    ['reflect-m5','Module 5 — Ethical Awareness'],
    ['reflect-m6','Module 6 — Motivation'],
    ['reflect-m7','Module 7 — Innovation & Diffusion'],
    ['capstone-q1','Capstone Q1 — Who has the final say?'],
    ['capstone-q2','Capstone Q2 — Who owns the failure?'],
    ['capstone-q3','Capstone Q3 — Which CQ capability first?'],
  ];

  const reflectionSection = reflectionKeys
    .filter(([k]) => state[k])
    .map(([k, label]) => `
      <h4 style="margin:16px 0 6px;font-size:.9rem;color:#495057">${label}</h4>
      <p style="font-size:.88rem;border-left:3px solid #0072B2;padding-left:12px;color:#212529">${(state[k]||'').replace(/\n/g,'<br>')}</p>
    `).join('') || '<p style="color:#adb5bd">No reflections saved.</p>';

  const planHTML = `
    <div style="margin-top:8px">
      ${['drive','knowledge','strategy','action'].map(c => `
        <div style="margin-bottom:12px">
          <strong style="font-size:.85rem;color:#495057;text-transform:uppercase;letter-spacing:.05em">${capLabels[c]}</strong>
          <p style="margin:4px 0 0;font-size:.88rem">${plan[c] || '—'}</p>
        </div>`).join('')}
    </div>`;

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>CQ Completion Record — ${name}</title>
<style>
  body { font-family: 'Inter',Arial,sans-serif; color: #212529; max-width: 720px; margin: 0 auto; padding: 32px 24px; font-size: 14px; }
  h1 { font-size: 22px; margin-bottom: 4px; }
  h2 { font-size: 16px; margin: 24px 0 10px; border-bottom: 2px solid #dee2e6; padding-bottom: 6px; }
  h3 { font-size: 14px; margin: 16px 0 6px; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 16px; }
  th { background: #f1f3f5; text-align: left; padding: 8px 12px; border: 1px solid #dee2e6; font-size: 12px; }
  td { padding: 8px 12px; border: 1px solid #dee2e6; vertical-align: top; }
  .header-box { border: 2px solid #0072B2; border-radius: 8px; padding: 20px 24px; text-align: center; margin-bottom: 28px; }
  .subhead { color: #6c757d; font-size: 13px; margin-top: 4px; }
  @media print {
    .no-print { display: none !important; }
    button { display: none; }
  }
</style>
</head>
<body>
<div class="header-box">
  <div style="font-size:1.6rem;margin-bottom:8px">🇮🇳</div>
  <h1>India CQ Training — Completion Record</h1>
  <p class="subhead">ENGR 802: Engineering Across Cultures · Penn State Great Valley</p>
  <p class="subhead"><strong>${name}</strong> · Completed: ${today}</p>
</div>

<h2>CQ Capability Scores (Before &amp; After)</h2>
<table>
  <tr><th>Capability</th><th>Before</th><th>After</th><th>Change</th></tr>
  ${scoreRows}
</table>

<h2>Personal 30-Day CQ Action Plan</h2>
${planHTML}

<h2>Module Reflections</h2>
${reflectionSection}

<p style="margin-top:32px;font-size:11px;color:#adb5bd;text-align:center">
  Generated by India CQ Training · ENGR 802 · Penn State Great Valley · ${today}
</p>

<div class="no-print" style="margin-top:24px;text-align:center">
  <button onclick="window.print()" style="padding:10px 24px;background:#0072B2;color:#fff;border:none;border-radius:6px;font-size:14px;font-weight:600;cursor:pointer">
    Print / Save as PDF
  </button>
</div>
</body>
</html>`;
}

function initCompletionDownload() {
  const btn = document.getElementById('download-completion');
  if (!btn) return;
  btn.addEventListener('click', () => {
    const html = buildCompletionHTML();
    const blob = new Blob([html], { type: 'text/html' });
    const url  = URL.createObjectURL(blob);
    const a    = document.createElement('a');
    a.href = url;
    a.download = 'CQ-Completion-Record.html';
    document.body.appendChild(a);
    a.click();
    setTimeout(() => { URL.revokeObjectURL(url); a.remove(); }, 1000);
  });
}

function initLearnerName() {
  const input = document.getElementById('learner-name-input');
  if (!input) return;
  const state = JSON.parse(localStorage.getItem('india-cq-v1') || '{}');
  if (state['learner-name']) input.value = state['learner-name'];
  input.addEventListener('input', () => {
    const s = JSON.parse(localStorage.getItem('india-cq-v1') || '{}');
    s['learner-name'] = input.value;
    localStorage.setItem('india-cq-v1', JSON.stringify(s));
  });
}

function renderCQDelta() {
  const container = document.getElementById('cq-delta-display');
  if (!container) return;
  const state = JSON.parse(localStorage.getItem('india-cq-v1') || '{}');
  const pre  = state['cq-pre-scores']  || {};
  const post = state['cq-post-scores'] || {};
  // Show results section (cq-postcheck page) once post scores are saved
  if (state['cq-post-scores']) {
    const results = document.getElementById('cq-results');
    if (results) results.style.display = 'block';
  }
  const caps = { drive:'CQ Drive', knowledge:'CQ Knowledge', strategy:'CQ Strategy', action:'CQ Action' };
  container.innerHTML = Object.entries(caps).map(([c, label]) => {
    const before = pre[c]  ?? null;
    const after  = post[c] ?? null;
    const delta  = (before !== null && after !== null) ? after - before : null;
    return `<div class="cq-delta-card">
      <div class="cq-delta-label">${label}</div>
      <div class="cq-delta-scores">
        <span class="cq-delta-before">${before ?? '—'}</span>
        <span class="cq-delta-arrow">→</span>
        <span class="cq-delta-after">${after ?? '—'}</span>
      </div>
      ${delta !== null ? `<div class="cq-delta-change ${delta>0?'up':delta<0?'down':'same'}">
        ${delta > 0 ? `+${delta} ↑` : delta < 0 ? `${delta} ↓` : 'No change'}
      </div>` : ''}
    </div>`;
  }).join('');
}

document.addEventListener('DOMContentLoaded', () => {
  initCompletionDownload();
  initLearnerName();
  renderCQDelta();
});
